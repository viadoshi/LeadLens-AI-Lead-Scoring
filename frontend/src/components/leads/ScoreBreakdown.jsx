import React from 'react';
import { SlidersHorizontal, Info } from 'lucide-react';
import { getIllustrativeScoringSignals } from '../../utils/mockLeadsData';

export default function ScoreBreakdown({ lead }) {
  const signals = getIllustrativeScoringSignals(lead);

  return (
    <div className="card score-breakdown-card">
      <div className="card-header-row">
        <div className="card-header-title-group">
          <div className="card-header-icon" aria-hidden="true">
            <SlidersHorizontal size={18} />
          </div>
          <div>
            <h2 className="section-heading">Score Breakdown</h2>
            <p className="card-header-subtitle">Illustrative scoring signals</p>
          </div>
        </div>

        <span className="illustrative-tag">
          UI Mockup Only
        </span>
      </div>

      {/* Prominent UI-only disclaimer banner per specification */}
      <div className="illustrative-disclaimer-banner" role="note">
        <Info size={15} className="disclaimer-icon" aria-hidden="true" />
        <span className="disclaimer-text">
          <strong>Illustrative scoring signals:</strong> These factors represent hypothetical UI-only demonstration signals and are <em>not</em> generated by an actual ML model. True model attribution (e.g. SHAP values) will be integrated in a future phase.
        </span>
      </div>

      <div className="signals-list">
        {signals.map((signal) => (
          <div key={signal.id} className="signal-row">
            <div className="signal-info">
              <div className="signal-name-group">
                <span className="signal-name">{signal.name}</span>
                <span className="signal-impact-badge">{signal.impact}</span>
              </div>
              <p className="signal-description">{signal.description}</p>
            </div>

            <div className="signal-meter-group">
              <div className="signal-bar-track" aria-hidden="true">
                <div
                  className="signal-bar-fill"
                  style={{
                    width: `${signal.percentage}%`,
                    backgroundColor:
                      signal.percentage >= 75
                        ? 'var(--accent)'
                        : signal.percentage >= 50
                        ? '#F59E0B'
                        : 'var(--text-dim)',
                  }}
                />
              </div>
              <span className="signal-contribution-text">{signal.contribution}</span>
            </div>
          </div>
        ))}
      </div>
    </div>
  );
}
