/**
 * Score interpretation derived dynamically from lead segment.
 * UI-only interpretation guideline per project specification.
 */
export function getScoreInterpretation(segment) {
  const normalized = (segment || '').toUpperCase();
  switch (normalized) {
    case 'HOT':
      return 'High conversion potential';
    case 'WARM':
      return 'Good potential with further qualification';
    case 'NURTURE':
      return 'Needs additional engagement';
    case 'COLD':
      return 'Low immediate conversion potential';
    default:
      return 'Potential pending qualification';
  }
}

