"""
Pydantic schemas for the LeadLens Analytics Dashboard endpoints.
"""
from typing import List, Optional
from pydantic import BaseModel, Field


class SummaryMetrics(BaseModel):
    """Headline aggregate performance KPIs."""
    total_leads: int = Field(..., description="Total leads arriving within selected date range", examples=[465])
    converted_leads: int = Field(..., description="Total leads converted to customers within selected range", examples=[98])
    conversion_rate: float = Field(..., description="Overall conversion rate percentage (converted / total * 100)", examples=[21.08])
    average_lead_score: float = Field(..., description="Mean lead scoring value across all leads in range", examples=[62.4])
    previous_period_leads: Optional[int] = Field(None, description="Total leads in immediately preceding equivalent duration")
    previous_period_conversions: Optional[int] = Field(None, description="Total conversions in immediately preceding duration")
    previous_period_conversion_rate: Optional[float] = Field(None, description="Conversion rate in preceding duration")
    leads_growth_pct: Optional[float] = Field(None, description="Percentage change in leads vs previous period")
    conversions_growth_pct: Optional[float] = Field(None, description="Percentage change in conversions vs previous period")
    conversion_rate_delta: Optional[float] = Field(None, description="Percentage point delta in conversion rate vs previous period")


class ConversionTrendItem(BaseModel):
    """Single date / period conversion trend observation."""
    date: str = Field(..., description="Formatted date or interval label", examples=["2026-10-21"])
    leads: int = Field(..., description="Total leads created in period", examples=[18])
    converted: int = Field(..., description="Leads converted in period", examples=[4])
    conversion_rate: float = Field(..., description="Conversion rate percentage for this specific period", examples=[22.2])


class SourcePerformanceItem(BaseModel):
    """Aggregate volume and conversion performance per lead channel / source."""
    source: str = Field(..., description="Lead acquisition source / channel name", examples=["Referral"])
    total_leads: int = Field(..., description="Total leads generated by this source", examples=[45])
    converted_leads: int = Field(..., description="Converted leads from this source", examples=[14])
    conversion_rate: float = Field(..., description="Source-level conversion percentage (converted / total * 100)", examples=[31.11])
    average_score: float = Field(..., description="Mean lead score of leads from this source", examples=[73.8])


class SegmentPerformanceItem(BaseModel):
    """Aggregate volume and conversion performance per LeadLens score tier."""
    segment: str = Field(..., description="Lead qualification tier (HOT, WARM, NURTURE, COLD)", examples=["HOT"])
    total_leads: int = Field(..., description="Count of leads classified in this tier", examples=[95])
    converted_leads: int = Field(..., description="Count of converted leads in this tier", examples=[69])
    conversion_rate: float = Field(..., description="Tier-level conversion percentage", examples=[72.63])
    average_score: float = Field(..., description="Mean lead score within this tier", examples=[86.4])


class CampaignPerformanceItem(BaseModel):
    """Aggregate volume and conversion yield per go-to-market campaign."""
    campaign: str = Field(..., description="Marketing or sales outbound campaign name", examples=["Cloud Scale Outreach"])
    total_leads: int = Field(..., description="Total leads attributed to this campaign", examples=[110])
    converted_leads: int = Field(..., description="Converted leads from this campaign", examples=[33])
    conversion_rate: float = Field(..., description="Campaign conversion yield percentage", examples=[30.0])
    average_score: float = Field(..., description="Mean lead score across this campaign", examples=[68.2])


class ScoreDistributionBucket(BaseModel):
    """Histogram bucket representing lead volume distribution across score bands."""
    bucket: str = Field(..., description="Score interval identifier (e.g. '0-19', '80-100')", examples=["80-100"])
    range_label: str = Field(..., description="Human-readable score band description", examples=["Score 80–100 (Hot)"])
    count: int = Field(..., description="Number of leads residing in this score band", examples=[95])
    percentage: float = Field(..., description="Percentage of total leads residing in this band", examples=[20.43])


class AnalyticsInsightItem(BaseModel):
    """Deterministic, data-supported business insight observation."""
    id: str = Field(..., description="Unique insight key identifier", examples=["insight-source-top"])
    type: str = Field(..., description="Visual sentiment type ('positive', 'opportunity', 'trend', 'neutral')", examples=["positive"])
    title: str = Field(..., description="Short executive insight headline", examples=["Highest Conversion Source"])
    description: str = Field(..., description="Data-supported explanation without speculative causation", examples=["Referral leads deliver the highest conversion yield at 31.1%."])
    metric_value: Optional[str] = Field(None, description="Optional callout stat or badge text", examples=["31.1%"])


class AnalyticsOverviewResponse(BaseModel):
    """Complete aggregated response payload for GET /api/analytics/overview."""
    range: str = Field(..., description="Requested time range filter ('7d', '30d', '90d', 'all')", examples=["30d"])
    range_label: str = Field(..., description="Human-readable range title", examples=["Last 30 Days"])
    anchor_date: str = Field(..., description="Reference date for chronological calculations (YYYY-MM-DD)", examples=["2026-10-27"])
    data_notice: str = Field("Demo workspace data", description="Notice indicating isolated business simulation data")
    summary: SummaryMetrics
    conversion_trend: List[ConversionTrendItem]
    source_performance: List[SourcePerformanceItem]
    segment_performance: List[SegmentPerformanceItem]
    campaign_performance: List[CampaignPerformanceItem]
    score_distribution: List[ScoreDistributionBucket]
    insights: List[AnalyticsInsightItem]
